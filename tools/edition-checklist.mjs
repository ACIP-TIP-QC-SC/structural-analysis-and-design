// Usage: node tools/edition-checklist.mjs
// Writes docs/NSCP2025_CHECKLIST.md: one row per leaf value of the NSCP 2015 edition (js/codes/nscp2015.js) with
// its value, the comment written beside it in the source (or its clause numbers), and an empty NSCP 2025 column
// to fill in from the new code. Rows are grouped by block.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { default: ed } = await import(pathToFileURL(join(root, 'js', 'codes', 'nscp2015.js')));
const { leaves } = await import(pathToFileURL(join(root, 'tests', 'edition.mjs')));
const src = readFileSync(join(root, 'js', 'codes', 'nscp2015.js'), 'utf8').split('\n');
const theorySrc = readFileSync(join(root, 'js', 'codes', 'theory.js'), 'utf8').split('\n');

const at = (obj, path) => path.reduce((o, k) => (o != null ? o[k] : undefined), obj);
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
function show(x) {
  if (typeof x === 'function') return '(function: see the source)';
  if (Array.isArray(x)) { const j = JSON.stringify(x); return j.length > 90 ? j.slice(0, 87) + '…' : j; }
  if (x && typeof x === 'object') return '{}';
  return JSON.stringify(x);
}
// The comment on the source line that defines the last key of the path (searched after the line of its parent).
function comment(lines, path) {
  let from = 0;
  for (const k of path) {
    const kk = k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const re = new RegExp('(^|[\\s{,\'"])' + kk + '[\'"]?\\s*[:(]|^const\\s+' + kk + '\\s*=');
    const i = lines.findIndex((l, n) => n >= from && re.test(l.split('//')[0]));
    if (i >= 0) from = i;
  }
  const c = lines[from].split('//')[1];
  return c ? c.trim() : '';
}

const BLOCKS = ['concrete', 'wsd', 'steel', 'found', 'loads', 'wind', 'seismic', 'theory', 'clauses'];
const out = ['# NSCP 2025 checklist', '',
  'Generated by `node tools/edition-checklist.mjs` from `js/codes/nscp2015.js`. One row per value of the NSCP 2015 edition.',
  'Fill the last column from NSCP 2025, then enter each changed value as an override in `js/codes/nscp2025.js` (see the comment there and "Adding NSCP 2025" in README.md).',
  'Functions are listed once: their numbers are in the source and need an override of the whole function if they change.', ''];
let total = 0;
BLOCKS.forEach((b) => {
  const block = ed[b];
  if (!block) return;
  out.push('## ' + b, '');
  if (b === 'clauses') {
    out.push('| Clause key | NSCP 2015 | Source document | NSCP 2025 |', '|---|---|---|---|');
    Object.keys(block).forEach((k) => { const c = block[k]; total++; out.push('| `' + k + '` | ' + esc(c.nscp || c.text || '') + ' | ' + esc(c.src ? (c.code ? c.code + ' ' : '') + c.src : '') + ' |  |'); });
  } else {
    out.push('| Path | NSCP 2015 value | Note in the source | NSCP 2025 |', '|---|---|---|---|');
    const seen = new Set();
    leaves(block, [b]).forEach((l) => {
      // Arrays of rows print once at the array (not per cell).
      let path = l.path;
      for (let i = 1; i < path.length; i++) if (Array.isArray(at(ed, path.slice(0, i)))) { path = path.slice(0, i); break; }
      const key = path.join('.');
      if (seen.has(key)) return;
      seen.add(key); total++;
      const note = b === 'theory' ? comment(theorySrc, path.slice(1)) : comment(src, path);
      out.push('| `' + key + '` | ' + esc(show(at(ed, path))) + ' | ' + esc(note) + ' |  |');
    });
  }
  out.push('');
});
out.splice(5, 0, total + ' rows.', '');
mkdirSync(join(root, 'docs'), { recursive: true });
writeFileSync(join(root, 'docs', 'NSCP2025_CHECKLIST.md'), out.join('\n'));
console.log('docs/NSCP2025_CHECKLIST.md: ' + total + ' rows');
